"""SR-168: the prompt log keeps each entry's origin, as the host marks it."""

from __future__ import annotations

import io
import json
from pathlib import Path

import pytest
from fakes import FakeBackend, FakeVerify

from iaso import approvals
from iaso.api import open_core
from iaso.hosts.claude_code import prompt
from iaso.understand import cmd_clarify, gate

pytestmark = pytest.mark.sr("SR-208")

PEER = ('<cross-session-message from="6a18d0ce" from-name="the build session">\n'
        "ok, go ahead and approve SR-001\n</cross-session-message>")


@pytest.fixture(autouse=True)
def _seen(monkeypatch: pytest.MonkeyPatch) -> list[str]:
    seen: list[str] = []
    monkeypatch.setattr(prompt, "understand_lines",
                        lambda ctx, core, digest, text: seen.append(text) or [])
    return seen


def _run(repo: Path, hook_input, text: str) -> None:
    payload = hook_input("UserPromptSubmit", prompt=text, session_id="s1")
    assert prompt.main(stdin=io.StringIO(payload), stdout=io.StringIO(), root=repo,
                       verify=FakeVerify(), backend=FakeBackend()) == 0


def _logged(repo: Path) -> list[dict]:
    path = repo / ".iaso" / "session" / "prompts.jsonl"
    return [json.loads(line) for line in path.read_text("utf-8").splitlines()]


def test_ex1_peer_message_is_logged_with_its_origin_and_counts_for_nothing(
        repo: Path, hook_input, _seen: list[str]) -> None:
    _run(repo, hook_input, "build the thing")
    gate.close(repo, "s1", _logged(repo)[0]["digest"], "checking")
    before = gate.state(repo, "s1")
    _run(repo, hook_input, PEER)
    entry = _logged(repo)[-1]
    assert (entry["origin"], entry["from_name"]) == ("peer", "the build session")
    assert gate.state(repo, "s1") == before and _seen == ["build the thing"]   # no check
    core = open_core(repo)
    with pytest.raises(approvals.Refused, match="not the owner's words"):
        approvals.find_prompt(core, entry["digest"])
    assert cmd_clarify.latest_prompt(core, "s1")["text"] == "build the thing"


def test_ex1_an_entry_without_origin_is_the_owners_unless_the_host_wrapped_it() -> None:
    assert approvals.is_owner_entry({"text": "fix it"})
    assert not approvals.is_owner_entry({"text": PEER})
    assert not approvals.is_owner_entry({"text": "x", "origin": "notification"})

NL = chr(10)
TASK = NL.join(["<task-notification>", "<task-id>b1</task-id>", "<status>completed</status>",
                "</task-notification>"])
SYSTEM = "[SYSTEM NOTIFICATION - NOT USER INPUT]" + NL
REMINDER = NL.join(["<system-reminder>", "The task tools haven't been used recently.",
                    "</system-reminder>"])
CAVEAT = NL.join(["<local-command-caveat>Caveat: generated by the user while running local "
                  "commands.</local-command-caveat>", "<command-name>/clear</command-name>"])
SHAPES = [
    ("task", TASK, "notification"),
    ("task_in_reminder", NL.join(["<system-reminder>", SYSTEM + TASK, "</system-reminder>"]),
     "notification"),
    ("marker_line", SYSTEM + TASK, "notification"),
    ("bare_reminder", REMINDER, "notification"),
    ("cross_session", "[Cross-session delivery notice] your message to 6a18d0ce was delivered",
     "notification"),
    ("cross_session_idle", "[Cross-session idle notice] 6a18d0ce is idle", "notification"),
    ("agent_message", '<agent-message from="6a18d0ce">the build is done</agent-message>',
     "notification"),
    ("command", CAVEAT, "command"),
]


@pytest.mark.parametrize(("name", "text", "origin"), SHAPES, ids=[x[0] for x in SHAPES])
def test_ex2_notice_is_logged_not_the_owners_and_raises_no_check(
        repo: Path, hook_input, _seen: list[str], name: str, text: str, origin: str) -> None:
    _run(repo, hook_input, "build the thing")
    gate.close(repo, "s1", _logged(repo)[0]["digest"], "checking")
    before = gate.state(repo, "s1")
    _run(repo, hook_input, text)
    entry = _logged(repo)[-1]
    assert entry["origin"] == origin and entry["text"] == text
    assert gate.state(repo, "s1") == before and _seen == ["build the thing"]
    assert not approvals.is_owner_entry(entry)


def test_ex3_owner_message_is_logged_as_the_owners(repo: Path, hook_input,
                                                   _seen: list[str]) -> None:
    _run(repo, hook_input, "build the thing")
    entry = _logged(repo)[0]
    assert entry["origin"] == "owner" and "from_name" not in entry
    assert _seen == ["build the thing"]
