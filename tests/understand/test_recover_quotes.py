def _real_jev(core, monkeypatch, urlopen):
    import urllib.request

    from plumb.judgment.jev import JevBackend, JevClient
    from plumb.judgment.tiers import Thresholds

    monkeypatch.setattr(urllib.request, "urlopen", urlopen)
    return JevBackend(core, JevClient(base_url="https://jev.invalid", key="k", timeout_s=1),
                      model="jev", validated_against=None, thresholds=Thresholds())


def test_jev_ranker_speaks_the_real_jev_request_and_answer_shapes(
        project: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Contract: the ranker's call goes through the real ``JevBackend`` and ``JevClient``
    (a canned HTTP answer, no network) and reads the real ``JudgmentRecord`` it returns."""
    import io

    from plumb.judgment.model import JudgmentRecord

    sent: list[dict] = []
    returned: list[JudgmentRecord] = []

    class Response(io.BytesIO):
        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    def urlopen(request, timeout=None):
        body = json.loads(request.data.decode("utf-8"))
        sent.append(body)
        labels = list(body["questions"]["source"]["criteria"])
        probabilities = {label: 0.02 for label in labels}
        probabilities["m1"] = round(1 - 0.02 * (len(labels) - 1), 6)
        return Response(json.dumps({
            "model": "jev-2026-10-01",
            "answers": {"source": {"type": "choice", "choice": "m1",
                                   "probabilities": probabilities, "confidence": 0.9}},
            "usage": {"input_tokens": 10}}).encode("utf-8"))

    backend = _real_jev(open_core(project), monkeypatch, urlopen)
    real_ask = backend._ask

    def ask(questions, prefix, paths=()):
        record = real_ask(questions, prefix, paths)
        returned.append(record)
        return record

    monkeypatch.setattr(backend, "_ask", ask)
    messages = [recover.Message(text=t, at=f"2026-10-0{n + 4}T00:00:00Z", session="s",
                                path="p") for n, t in enumerate((OCT4, DIGEST, OTHER))]
    view = recover.record_view(open_core(project).index()["INT-020"])
    ranked = recover.JevRanker(backend).rank(view, messages)

    (body,) = sent
    assert body["model"] == "jev" and isinstance(body["state"], str)
    question = body["questions"]["source"]
    assert question["type"] == "choice"
    assert question["instructions"] == recover.JevRanker.QUESTION
    assert set(question["criteria"]) == {"m0", "m1", "m2", "none"}
    assert DIGEST in body["state"] and "INT-020" in body["state"]
    (record,) = returned
    assert isinstance(record, JudgmentRecord) and record.outcome == "ok"
    assert record.answers["source"].kind == "choice"
    assert record.answers["source"].value == "m1"
    assert ranked[0] == (pytest.approx(0.94), 1)
    assert sorted(i for _, i in ranked) == [0, 1, 2]


def test_jev_ranker_reports_an_unreachable_real_backend(project: Path,
                                                        monkeypatch: pytest.MonkeyPatch) -> None:
    import urllib.error

    def urlopen(request, timeout=None):
        raise urllib.error.URLError("timed out")

    backend = _real_jev(open_core(project), monkeypatch, urlopen)
    with pytest.raises(recover.RecoveryError, match="JEV"):
        recover.JevRanker(backend).rank({"id": "INT-020"}, [recover.Message(
            text=DIGEST, at="2026-10-06", session="s", path="p")])
