"""``plumb view``: the records as a generated Obsidian vault and a Canvas intent map
(R9 DEEP REVIEW, sp5 7, SR-066).

"la grappe d'artefacts": one note per record (frontmatter state, hash and badges; the body
in the owner's terms), example, test and code notes, ``[[wikilinks]]`` along
INT -> SR -> EX -> tests -> code with backlinks, index notes (``index.md``,
``by-feature.md``, ``awaiting-you.md``, ``drift.md``) and ``intent-map.canvas``
(JSON Canvas 1.0).

It is generated, never hand-edited: every file carries "generated by plumb view; edits are
overwritten", regenerating is byte-identical for the same records and evidence, and files of
records that no longer exist are removed. plumb never reads the vault back, so editing a note
approves nothing: confirmation stays ``plumb triage`` / ``plumb approve`` in the owner's
terminal or "ok" in a session. The default folder, ``.plumb/view/``, is gitignored.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

GENERATED = "generated by plumb view; edits are overwritten"
_SLUG = re.compile(r"[^A-Za-z0-9._-]+")
COLORS = {"confirmed": "4", "proposed": "3", "unconfirmed-edit": "2", "red": "1"}
CARD_W, CARD_H = 280, 120


def slug(text: str) -> str:
    return _SLUG.sub("-", text.replace("::", "--").replace("/", "__")).strip("-")


def test_note(end: str) -> str:
    return f"test--{slug(end)}"


def code_note(end: str) -> str:
    return f"code--{slug(end)}"


def _flat(value: Any) -> str:
    if isinstance(value, list):
        return " / ".join(" ".join(str(v).split()) for v in value)
    return " ".join(str(value or "").split())


def _yaml(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _items(raw: Any) -> list[str]:
    from plumb.present.cards import _items as items

    return list(items(raw))


class Vault:
    """Builds every file's text in memory, then writes what changed."""

    def __init__(self, core: Any, scope: Sequence[str] | None = None) -> None:
        from plumb.query import superseded_ids

        self.core = core
        self.index = core.index()
        self.statuses = core.status()
        self.superseded = superseded_ids(self.index)
        self.files: dict[str, str] = {}
        wanted = set(scope) if scope else set(self.index)
        if scope:  # a scoped view keeps the chain of each record
            for record_id in list(wanted):
                record = self.index.get(record_id)
                for link in getattr(record, "links", ()):
                    if link.target.record in self.index:
                        wanted.add(link.target.record)
        self.ids = sorted(i for i in wanted if i in self.index)
        self.failing = self._failing()
        self.edge_badges = self._edge_badges()
        self.hints = self._hints()

    # -- data
    def _failing(self) -> set[str]:
        try:
            from plumb.commands import acceptance_failures

            return set(acceptance_failures(self.core))
        except Exception:  # noqa: BLE001 - VERIFY absent: nothing failing known
            return set()

    def _edge_badges(self) -> dict[tuple[str, str], str]:
        try:
            from plumb.align import align, badge

            result = align(self.core, [i for i in self.ids
                                       if self.index[i].kind == "requirement"] or None)
        except Exception:  # noqa: BLE001 - alignment is advisory
            return {}
        return {(e.source, e.target): f"{badge(e)}" + (f" {e.score:.2f}" if e.score
                                                         is not None else "")
                for e in result.edges}

    def _hints(self) -> set[str]:
        try:
            from plumb.capture import api

            lines = api.drift_hints(self.core, [])
        except Exception:  # noqa: BLE001 - CAPTURE absent: no hint badges
            return set()
        from plumb.query import _ID_IN_TEXT

        return {i for line in lines for i in _ID_IN_TEXT.findall(str(line))}

    def state(self, record_id: str) -> str:
        status = self.statuses.get(record_id)
        return status.confirmation if status is not None else "proposed"

    def confirmed_by(self, record_id: str) -> str | None:
        """"you", "JEV", "you (relayed), self-recorded message": the label every surface
        uses (``present.cards.confirmed_label``, R8 B, R13 Q4), without "confirmed by"."""
        from plumb.present.cards import confirmed_label

        label = confirmed_label(self.core, record_id, self.statuses.get(record_id))
        return label.removeprefix("confirmed by ") if label else None

    def badges(self, record_id: str) -> list[str]:
        status = self.statuses.get(record_id)
        out = []
        if status is not None and any(s.state == "stale" for s in status.links):
            out.append("stale")
        if record_id in self.failing:
            out.append("failing")
        state = self.state(record_id)
        if state == "proposed":
            out.append("proposed")
        if state != "confirmed" and record_id not in self.superseded:
            out.append("awaits-you")
        if status is not None and status.approved_by == "auto-jev" and state == "confirmed":
            out.append("confirmed-by-jev")
        if record_id in self.hints:
            out.append("hint")
        return out

    def tests_of(self, ends: Sequence[str]) -> dict[str, str]:
        from plumb.present.cards import test_states

        return test_states(self.core, list(ends)) if ends else {}

    # -- notes
    def head(self, meta: Mapping[str, Any]) -> list[str]:
        lines = ["---", f"# {GENERATED}"]
        for key, value in meta.items():
            lines.append(f"{key}: {_yaml(value)}")
        lines.append("---")
        return lines

    def record_note(self, record_id: str) -> None:
        from plumb.present.cards import example_text

        record = self.index[record_id]
        fields = record.fields
        state = self.state(record_id)
        badges = self.badges(record_id)
        meta = {"id": record_id, "kind": record.kind, "title": record.title, "state": state,
                "confirmed_by": self.confirmed_by(record_id), "hash": record.hash,
                "feature": fields.get("feature"), "badges": badges, "tags": badges}
        out = self.head(meta)
        out.append(f"# {record_id} {record.title}")
        out.append("")
        by = self.confirmed_by(record_id)
        out.append(f"State: **{state}**" + (f", confirmed by {by}" if by else ""))
        for name in badges:
            kind = "warning" if name in ("stale", "failing") else "note"
            out.append("")
            out.append(f"> [!{kind}] #{name}")
        if fields.get("quote"):
            from plumb.text import quote_label

            label = quote_label(fields)
            out += ["", f"{label[0].upper()}{label[1:]}: \"{_flat(fields['quote'])}\""]
        for key, label in (("readback", "Read-back"), ("statement", "Statement"),
                           ("description", "Description"), ("question", "Question"),
                           ("chosen", "Chosen")):
            if fields.get(key):
                out += ["", f"{label}: {_flat(fields[key])}"]
        for key, label in (("will", "Will"), ("wont", "Won't"), ("assumptions", "Assumed"),
                           ("alternatives", "Also fits")):
            items = _items(fields.get(key))
            if items:
                out += ["", f"{label}:"] + [f"- {item}" for item in items]
        ends = [(link, link.target.test or link.target.path) for link in record.links
                if link.kind == "verified_by" and (link.target.test or link.target.path)]
        tests = self.tests_of([end for _, end in ends])
        if record.examples:
            out += ["", "## Examples"]
            for example in record.examples:
                out.append(f"- [[{record_id}.{example.id}]] {example_text(example)}")
        up = [link for link in record.links if link.target.record]
        if up:
            out += ["", "## Linked records"]
            for link in up:
                badge = self.edge_badges.get((link.target.record, record_id)) or \
                    self.edge_badges.get((record_id, link.target.record or ""))
                out.append(f"- {link.kind} [[{link.target.record}]]"
                           + (f" (alignment: {badge})" if badge else ""))
        feature = fields.get("feature")
        if feature in self.index:
            out.append(f"- feature [[{feature}]]")
        if ends:
            out += ["", "## Tests"]
            for link, end in ends:
                source = f"{record_id}/{link.example}" if link.example else record_id
                badge = self.edge_badges.get((source, end))
                out.append(f"- [[{test_note(end)}|{end}]] {tests.get(end, 'not run')}"
                           + (f" ({link.example})" if link.example else "")
                           + (f" (alignment: {badge})" if badge else ""))
        code = [link.target.path or str(link.target.symbol) for link in record.links
                if link.kind == "implemented_by"]
        if code:
            out += ["", "## Code"]
            for end in code:
                badge = self.edge_badges.get((record_id, end))
                out.append(f"- [[{code_note(end)}|{end}]]"
                           + (f" (alignment: {badge})" if badge else ""))
        below = sorted(r.id for r in self.index.values() if any(
            link.target.record == record_id for link in r.links)
            or str(r.fields.get("feature")) == record_id)
        if below:
            out += ["", "## Led to"] + [f"- [[{i}]] {self.index[i].title}" for i in below]
        if state != "confirmed":
            out += ["", "## Confirm (your terminal, or say \"ok\" in a session)",
                    f"`plumb approve {record_id}`",
                    "Editing this note approves nothing: plumb never reads it."]
        if record.body.strip():
            out += ["", "## Notes", record.body.strip()]
        self.files[f"{record_id}.md"] = "\n".join(out) + "\n"
        for example in record.examples:
            self.example_note(record, example, ends, tests)
        for link, end in ends:
            self.add_backlink(test_note(end), end, "test", record_id, link.example, tests)
        for end in code:
            self.add_backlink(code_note(end), end, "code", record_id, None, {})

    def example_note(self, record: Any, example: Any, ends: Sequence[tuple[Any, str]],
                     tests: Mapping[str, str]) -> None:
        name = f"{record.id}.{example.id}"
        out = self.head({"id": name, "kind": "example", "requirement": record.id,
                         "state": self.state(record.id)})
        out += [f"# {name}", "", f"Example of [[{record.id}]] {record.title}", ""]
        if example.given or example.when or example.then:
            out += [f"- given {example.given}", f"- when {example.when}",
                    f"- then {example.then}"]
        else:
            out.append(f"- {example.criterion}")
        verifying = [end for link, end in ends if link.example == example.id]
        out += ["", "## Tests"]
        out += [f"- [[{test_note(e)}|{e}]] {tests.get(e, 'not run')}" for e in verifying] \
            or ["- none (a gap: no test checks this example)"]
        self.files[f"{name}.md"] = "\n".join(out) + "\n"

    def add_backlink(self, note: str, end: str, kind: str, record_id: str,
                     example: str | None, tests: Mapping[str, str]) -> None:
        key = f"{note}.md"
        line = f"- [[{record_id}.{example}]] of [[{record_id}]]" if example \
            else f"- [[{record_id}]]"
        line += f" {self.index[record_id].title}"
        existing = self.files.get(key)
        if existing is None:
            out = self.head({"id": end, "kind": kind}
                            | ({"state": tests.get(end, "not run")} if kind == "test" else {}))
            title = "verifies" if kind == "test" else "implements"
            out += [f"# {end}", "", f"This {kind} {title}:"]
            existing = "\n".join(out) + "\n"
        if line not in existing:
            existing += line + "\n"
        self.files[key] = existing

    # -- index notes
    def index_notes(self) -> None:
        kinds = {"intent": "Intents", "feature": "Features", "requirement": "Requirements",
                 "decision": "Decisions", "nc": "Nonconformances"}
        out = self.head({"id": "index", "kind": "index"})
        out += ["# plumb records", "",
                "[[by-feature]] · [[awaiting-you]] · [[drift]] · intent map: "
                "intent-map.canvas", ""]
        for kind, label in kinds.items():
            ids = [i for i in self.ids if self.index[i].kind == kind]
            if ids:
                out += [f"## {label} ({len(ids)})"] + [
                    f"- [[{i}]] {self.index[i].title} ({self.state(i)})" for i in ids] + [""]
        self.files["index.md"] = "\n".join(out).rstrip("\n") + "\n"

        out = self.head({"id": "by-feature", "kind": "index"})
        out += ["# By feature", ""]
        features = [i for i in self.ids if self.index[i].kind == "feature"]
        grouped: set[str] = set()
        for feature in features:
            members = sorted({str(m) for m in self.index[feature].fields.get("requirements")
                              or [] if str(m) in self.index}
                             | {r for r in self.ids if self.index[r].kind == "requirement"
                                and str(self.index[r].fields.get("feature")) == feature})
            grouped |= set(members)
            out += [f"## [[{feature}]] {self.index[feature].title}"] + [
                f"- [[{m}]] {self.index[m].title} ({self.state(m)})" for m in members] + [""]
        loose = [i for i in self.ids if self.index[i].kind == "requirement"
                 and i not in grouped]
        if loose:
            out += ["## No feature"] + [f"- [[{i}]] {self.index[i].title}" for i in loose]
        self.files["by-feature.md"] = "\n".join(out).rstrip("\n") + "\n"

        out = self.head({"id": "awaiting-you", "kind": "index"})
        out += ["# Awaiting you", "",
                "Confirm in your own terminal (copy a command) or say \"ok\" in a session. "
                "Editing these notes approves nothing.", "",
                "- the low-risk group: `plumb triage --approve low-risk`", ""]
        waiting = [i for i in self.ids if self.state(i) != "confirmed"
                   and i not in self.superseded]
        out += [f"- [[{i}]] {self.index[i].title} ({self.state(i)}): `plumb approve {i}`"
                for i in waiting] or ["- nothing"]
        self.files["awaiting-you.md"] = "\n".join(out) + "\n"

        out = self.head({"id": "drift", "kind": "index"})
        out += ["# Drift", ""]
        for record_id in self.ids:
            status = self.statuses.get(record_id)
            for link_state in getattr(status, "links", ()):
                if link_state.state in ("stale", "dangling"):
                    target = link_state.link.target
                    end = target.record or target.test or target.path or target.symbol
                    out.append(f"- [[{record_id}]] {link_state.link.id} {link_state.state} "
                               f"-> {end}")
            if status is not None and status.confirmation == "unconfirmed-edit":
                out.append(f"- [[{record_id}]] changed since you confirmed it")
            if record_id in self.failing:
                out.append(f"- [[{record_id}]] failing acceptance test")
        weak = sorted((k, v) for k, v in self.edge_badges.items() if v.startswith("weak"))
        if weak:
            out += ["", "## Weak edges (alignment, advisory)"] + [
                f"- {a} -> {b}: {v}" for (a, b), v in weak]
        if len(out) == len(self.head({"id": "drift", "kind": "index"})) + 2:
            out.append("- none")
        self.files["drift.md"] = "\n".join(out) + "\n"

    # -- canvas
    def canvas(self) -> None:
        nodes: list[dict[str, Any]] = [{"id": "generated", "type": "text", "text": GENERATED,
                                        "x": 0, "y": -160, "width": 400, "height": 60}]
        edges: list[dict[str, Any]] = []
        intents = [i for i in self.ids if self.index[i].kind == "intent"]
        features = [i for i in self.ids if self.index[i].kind == "feature"]
        requirements = [i for i in self.ids if self.index[i].kind == "requirement"]

        def color(record_id: str) -> str:
            badges = self.badges(record_id)
            if "stale" in badges or "failing" in badges:
                return COLORS["red"]
            return COLORS.get(self.state(record_id), COLORS["proposed"])

        def node(record_id: str, x: int, y: int) -> None:
            nodes.append({"id": record_id, "type": "file", "file": f"{record_id}.md",
                          "x": x, "y": y, "width": CARD_W, "height": CARD_H,
                          "color": color(record_id)})

        for n, record_id in enumerate(intents):
            node(record_id, 0, n * (CARD_H + 40))
        row = 0
        placed: set[str] = set()
        for feature in features:
            node(feature, 400, row * (CARD_H + 40))
            members = [r for r in requirements if str(self.index[r].fields.get("feature"))
                       == feature or r in {str(m) for m in self.index[feature].fields.get(
                           "requirements") or []}]
            for n, record_id in enumerate(members):
                if record_id in placed:
                    continue
                placed.add(record_id)
                node(record_id, 800 + (n % 4) * (CARD_W + 40),
                     (row + n // 4) * (CARD_H + 40))
                edges.append({"id": f"{feature}->{record_id}", "fromNode": feature,
                              "toNode": record_id, "label": "feature"})
            row += max(1, (len(members) + 3) // 4)
        loose = [r for r in requirements if r not in placed]
        for n, record_id in enumerate(loose):
            node(record_id, 800 + (n % 4) * (CARD_W + 40), (row + n // 4) * (CARD_H + 40))
        shown = {n["id"] for n in nodes}
        for record_id in self.ids:
            for link in self.index[record_id].links:
                target = link.target.record
                if target in shown and record_id in shown and link.kind in (
                        "derives_from", "upstream"):
                    edges.append({"id": f"{record_id}#{link.index}", "fromNode": record_id,
                                  "toNode": target, "label": link.kind})
        data = {"nodes": nodes, "edges": sorted(edges, key=lambda e: e["id"])}
        self.files["intent-map.canvas"] = json.dumps(data, indent=1, ensure_ascii=False) + "\n"

    def build(self) -> dict[str, str]:
        for record_id in self.ids:
            self.record_note(record_id)
        self.index_notes()
        self.canvas()
        return self.files


def write_vault(core: Any, out: Path, *, scope: Sequence[str] | None = None) -> dict[str, Any]:
    """Write the vault to ``out``: changed files only, and generated files of records that
    no longer exist removed. Returns ``{notes, written, removed, out}``."""
    files = Vault(core, scope).build()
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    written = 0
    for name, text in sorted(files.items()):
        path = out / name
        data = text.encode("utf-8")
        try:
            if path.read_bytes() == data:
                continue
        except OSError:
            pass
        path.write_bytes(data)
        written += 1
    removed = 0
    for path in sorted(list(out.glob("*.md")) + list(out.glob("*.canvas"))):
        if path.name in files:
            continue
        try:
            if GENERATED in path.read_text(encoding="utf-8", errors="replace")[:400]:
                path.unlink()
                removed += 1
        except OSError:
            pass
    return {"notes": len(files), "written": written, "removed": removed, "out": str(out)}


def open_vault(out: Path) -> None:
    """Open the vault folder: Obsidian's URI when it is registered, else the platform's
    opener. Never called by the tests."""
    target = str(Path(out).resolve())
    try:
        if sys.platform.startswith("win"):
            os.startfile(target)  # type: ignore[attr-defined]  # noqa: S606
        elif sys.platform == "darwin":
            subprocess.run(["open", target], check=False)
        else:
            subprocess.run(["xdg-open", target], check=False)
    except OSError:
        print(f"plumb view: open {target} in Obsidian (Open folder as vault)")
