"""plumb for Hermes: a thin adapter over plumb's host-neutral turn API (sp4 4.3).

Generated by `plumb hosts install hermes`; regenerate it rather than editing it.

Hermes runs its own interpreter, so each event runs one `plumb hook <event> --host hermes
--format json` process and renders its TurnOutput: agent_context as the turn's context
(`pre_llm_call`), a block at most once per turn (`pre_verify`, attempt 0), owner_lines
appended to the reply (`transform_llm_output`), the status in `plumb status`. A summary that
did not reach the owner is recorded as unseen (`--unseen`). Child agents (delegation,
background review, cron) are skipped: their messages are never the owner's words.
`register(ctx)` sets the session marker in Hermes' environment, which its local terminal
tool inherits; the owner-terminal guard holds whether or not it is set.
"""

from __future__ import annotations

import json
import os
import subprocess
from typing import Any

PLUMB: list[str] = ["plumb"]  # plumb:argv (set by plumb hosts install hermes)
MARKER = "PLUMB_AGENT_SESSION"
TIMEOUT_S = 5.0
EDIT_TOOLS = {"write_file", "patch"}
EMPTY: dict[str, Any] = {"agent_context": [], "owner_lines": [], "block": None,
                         "status_line": ""}

_briefs: dict[str, list[str]] = {}
_stopped: set[str] = set()
_children: set[str] = set()     # sessions of in-process child agents (delegation, review)
_summaries: dict[str, str] = {}  # session -> the summary appended to its reply, not yet seen


def _argv(event: str, *flags: str) -> list[str]:
    return [*PLUMB, "hook", event, "--host", "hermes", "--format", "json", *flags]


def _parse(stdout: str) -> dict[str, Any]:
    text = (stdout or "").strip()
    if not text:
        return dict(EMPTY)
    try:
        data = json.loads(text)
    except ValueError:
        return {**EMPTY, "agent_context": text.splitlines()}
    if not isinstance(data, dict):
        return dict(EMPTY)
    if isinstance(data.get("systemMessage"), str):  # a budget or error notice
        return {**EMPTY, "owner_lines": data["systemMessage"].splitlines()}
    return {**EMPTY, **data}


def _run(event: str, payload: dict[str, Any], *flags: str,
         background: bool = False) -> dict[str, Any]:
    cwd = os.getcwd()
    data = json.dumps({**payload, "cwd": cwd})
    try:
        if background:
            child = subprocess.Popen(_argv(event, *flags), stdin=subprocess.PIPE,
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                     cwd=cwd, text=True, encoding="utf-8")
            child.stdin.write(data)
            child.stdin.close()
            return dict(EMPTY)
        result = subprocess.run(_argv(event, *flags), input=data, capture_output=True,
                                text=True, encoding="utf-8", errors="replace",
                                timeout=TIMEOUT_S, cwd=cwd)
    except (OSError, subprocess.SubprocessError):
        return dict(EMPTY)  # plumb never blocks the agent's work on its own failure
    return _parse(result.stdout)


def _session(kwargs: dict[str, Any]) -> str:
    return str(kwargs.get("session_id") or kwargs.get("task_id") or "hermes")


def _owner_session(kwargs: dict[str, Any]) -> str | None:
    """The session when this hook belongs to the owner's own agent, else None.

    Hermes runs delegated subagents, its background review and cron runs in-process: their
    turns fire the same hooks, with ``parent_session_id`` set on ``pre_llm_call``. Their
    "user message" is text an agent wrote, never the owner's words, and their reply goes to
    the parent agent, never to the owner. So plumb logs no prompt, runs no stop and appends
    no summary for them: every hook asks here first."""
    session = _session(kwargs)
    if kwargs.get("parent_session_id"):
        _children.add(session)
    return None if session in _children else session


def _stop(session: str, *, active: bool) -> dict[str, Any]:
    """The stop event; transform_llm_output appends its summary to the reply."""
    _stopped.add(session)
    out = _run("stop", {"session_id": session, "stop_active": active})
    _summaries[session] = "\n".join(str(line) for line in out.get("owner_lines") or [])
    return out


def _settle(session: str, reply: str | None) -> None:
    """The owner saw this turn's summary only if it is in the reply Hermes returned. When it
    is not (the turn was interrupted, the reply was empty, another plugin's transform won),
    rerun the stop event ``--unseen``: no record of the stated set stays marked shown, so a
    bare "ok" relays none of them."""
    summary = _summaries.pop(session, None)
    if summary is None or (reply is not None and summary in reply):
        return
    _run("stop", {"session_id": session, "stop_active": True}, "--unseen")


def on_session_start(**kwargs: Any) -> None:
    session = _owner_session(kwargs)
    if session is None:
        return
    out = _run("session-start", {"session_id": session, "source": "startup"})
    _briefs[session] = list(out["agent_context"])  # rides on the first pre_llm_call


def pre_llm_call(**kwargs: Any) -> dict[str, str] | None:
    session = _owner_session(kwargs)
    if session is None:  # a child agent's goal is not the owner's prompt
        return None
    _settle(session, None)  # the last reply ended without showing its summary
    _stopped.discard(session)  # a new owner message starts a new turn
    out = _run("prompt", {"session_id": session, "text": str(kwargs.get("user_message") or "")})
    lines = [*_briefs.pop(session, []), *out["agent_context"]]
    return {"context": "\n".join(lines)} if lines else None


def post_tool_call(**kwargs: Any) -> None:
    if kwargs.get("tool_name") not in EDIT_TOOLS:
        return
    args = kwargs.get("args") if isinstance(kwargs.get("args"), dict) else {}
    path = args.get("path") or args.get("file_path")
    session = _owner_session(kwargs)
    if isinstance(path, str) and session is not None:
        _run("post-edit", {"session_id": session, "path": path}, background=True)


def pre_verify(**kwargs: Any) -> dict[str, str] | None:
    session = _owner_session(kwargs)
    if session is None:
        return None
    attempt = int(kwargs.get("attempt") or 0)
    out = _stop(session, active=attempt > 0)
    if out.get("block") and attempt == 0:
        _summaries.pop(session, None)  # a blocked stop shows the owner nothing
        return {"decision": "block", "reason": str(out["block"])}
    return None


def transform_llm_output(**kwargs: Any) -> str | None:
    """The owner's channel: the turn's summary (owner_lines) is appended to the reply."""
    session = _owner_session(kwargs)
    reply = kwargs.get("response_text")
    if session is None or not isinstance(reply, str) or not reply:
        return None
    if session not in _summaries:  # no edits (no pre_verify), or only a blocked stop
        _stop(session, active=True)  # status and summary only, never a block
    summary = _summaries.get(session)
    return f"{reply}\n\n{summary}" if summary else None


def post_llm_call(**kwargs: Any) -> None:
    session = _owner_session(kwargs)
    if session is None:
        return
    if session not in _stopped:  # no transform_llm_output on this Hermes: nothing shown
        _stopped.add(session)
        _run("stop", {"session_id": session, "stop_active": True}, "--unseen")
        return
    reply = kwargs.get("assistant_response")
    _settle(session, reply if isinstance(reply, str) else "")


HOOKS = (("on_session_start", on_session_start), ("pre_llm_call", pre_llm_call),
         ("post_tool_call", post_tool_call), ("pre_verify", pre_verify),
         ("transform_llm_output", transform_llm_output), ("post_llm_call", post_llm_call))


def register(ctx: Any) -> None:
    os.environ[MARKER] = "hermes"
    register_hook = getattr(ctx, "register_hook", None)
    if callable(register_hook):
        for name, callback in HOOKS:
            try:
                register_hook(name, callback)
            except Exception:  # noqa: BLE001 - an older Hermes without this hook
                pass

    def command(raw_args: str = "") -> str:
        # exactly the owner's words: the message is logged as the owner's prompt, so plumb
        # adds nothing to it (no word of plumb's could then be relayed as the owner's ok)
        words = (raw_args or "").strip() or "status"
        message = f"/plumb {words}"
        inject = getattr(ctx, "inject_message", None)
        if callable(inject):
            try:
                if inject(message):
                    return f"plumb: passed to the agent: {words}"
            except Exception:  # noqa: BLE001
                pass
        return f"plumb: ask the agent: {message}"

    ctx.register_command("plumb", command,
                         description="plumb: explain, status, review or confirm, in your words")
