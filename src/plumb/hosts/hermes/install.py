"""``plumb hosts install|uninstall|status hermes`` (sp4 4.3, SR-056).

Renders the project plugin ``.hermes/plugins/plumb/{plugin.yaml,__init__.py,plugin.py}``
(``register(ctx)`` registers ``on_session_start``, ``pre_llm_call``, ``post_tool_call``,
``pre_verify``, ``post_llm_call`` and the ``/plumb`` command, and sets the session marker) and
the instruction block of the CLI-only fallback in the context file Hermes loads
(``.hermes.md`` or ``HERMES.md`` when the project has one, else ``AGENTS.md``). Hermes loads
project plugins only with ``HERMES_ENABLE_PROJECT_PLUGINS=1``.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

from plumb.hosts.common import (
    InstallReport,
    context_file,
    has_block,
    instruction_block,
    launcher_argv,
    marker_lines,
    prompt_lines,
    rel,
    remove_file,
    remove_shared_block,
    upsert_block,
    write_file,
)

HOST = "hermes"
PLUGIN_DIR = Path(".hermes") / "plugins" / "plumb"
FILES = ("plugin.yaml", "__init__.py", "plugin.py")
TEMPLATES = Path(__file__).parent / "templates"
GENERATED = "Generated by `plumb hosts install hermes`"
_ARGV_LINE = re.compile(r"^PLUMB: list\[str\] = .*# plumb:argv.*$", re.MULTILINE)
ENABLE_ENV = "HERMES_ENABLE_PROJECT_PLUGINS"


def render(name: str, argv: list[str]) -> str:
    text = (TEMPLATES / name).read_text(encoding="utf-8")
    if name == "plugin.py":
        line = f"PLUMB: list[str] = {argv!r}  # plumb:argv (set by plumb hosts install hermes)"
        text = _ARGV_LINE.sub(lambda _m: line, text)
    return text


def _ours(path: Path) -> bool:
    try:
        return GENERATED in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def install(root: Path, *, launcher: str = "auto", dry_run: bool = False) -> InstallReport:
    root = Path(root)
    report = InstallReport()
    argv = launcher_argv(root, launcher)
    upsert_block(root, context_file(root, HOST), instruction_block(argv, HOST, hooks=True),
                 report, dry_run)
    for name in FILES:
        target = root / PLUGIN_DIR / name
        if target.exists() and not _ours(target):
            report.lines.append(f"{rel(root, target)} kept: it is not plumb's; nothing "
                                "written there")
            continue
        write_file(root, target, render(name, argv), report, dry_run)
    report.lines.append(f"Hermes loads project plugins only with {ENABLE_ENV}=1; until then "
                        "the context-file fallback applies")
    return report


def uninstall(root: Path, *, dry_run: bool = False) -> InstallReport:
    root = Path(root)
    report = InstallReport()
    for name in FILES:
        target = root / PLUGIN_DIR / name
        if target.exists() and _ours(target):
            remove_file(root, target, report, dry_run)
    remove_shared_block(root, HOST, report, dry_run)
    return report


def status(root: Path) -> list[str]:
    root = Path(root)
    installed = all(_ours(root / PLUGIN_DIR / name) for name in FILES)
    enabled = os.environ.get(ENABLE_ENV, "").strip().lower() in ("1", "true", "yes", "on")
    active = installed and enabled
    where = context_file(root, HOST)
    lines = ["plugin: " + (PLUGIN_DIR.as_posix() if installed else "not installed")
             + (f" ({ENABLE_ENV}=1 set)" if enabled else f" (needs {ENABLE_ENV}=1)"),
             "instruction block: " + ("present" if has_block(where) else "missing")
             + f" ({rel(root, where)}, plumb turn start/end)"]
    lines += marker_lines(active, "by the plugin in Hermes' environment (local terminal)")
    lines += prompt_lines(root, active, "pre_llm_call")
    return lines
