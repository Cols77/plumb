"""``plumb hosts install|uninstall|status pi`` (sp4 4.2, SR-055).

Renders ``.pi/extensions/plumb/index.ts`` (a thin TypeScript layer: Pi events to
``plumb hook <event> --host pi --format json``, the footer status, notices, one follow-up per
block, the ``/plumb`` command and the session marker in the extension's process environment)
and the ``AGENTS.md`` block of the CLI-only fallback. Idempotent; foreign files and the
owner's own ``AGENTS.md`` text are never touched. Pi loads project extensions only once the
project is trusted.
"""

from __future__ import annotations

import json
from pathlib import Path

from plumb.hosts.common import (
    InstallReport,
    context_file,
    has_block,
    instruction_block,
    launcher_argv,
    marker_lines,
    prompt_lines,
    remove_file,
    remove_shared_block,
    upsert_block,
    write_file,
)

HOST = "pi"
EXTENSION = Path(".pi") / "extensions" / "plumb" / "index.ts"
TEMPLATE = Path(__file__).parent / "templates" / "index.ts"
GENERATED = "Generated by `plumb hosts install pi`"


def render(argv: list[str]) -> str:
    """The extension's source, with the launcher's argv."""
    text = TEMPLATE.read_text(encoding="utf-8")
    return text.replace("__PLUMB_ARGV__", json.dumps(argv))


def _ours(path: Path) -> bool:
    try:
        return GENERATED in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def install(root: Path, *, launcher: str = "auto", dry_run: bool = False) -> InstallReport:
    root = Path(root)
    report = InstallReport()
    argv = launcher_argv(root, launcher)
    upsert_block(root, context_file(root, HOST), instruction_block(argv, HOST, hooks=True),
                 report, dry_run)
    target = root / EXTENSION
    if target.exists() and not _ours(target):
        report.lines.append(f"{EXTENSION.as_posix()} kept: it is not plumb's; nothing "
                            "written there")
    else:
        write_file(root, target, render(argv), report, dry_run)
    report.lines.append("Pi loads project extensions once you trust the project; until then "
                        "the AGENTS.md fallback applies")
    return report


def uninstall(root: Path, *, dry_run: bool = False) -> InstallReport:
    root = Path(root)
    report = InstallReport()
    target = root / EXTENSION
    if target.exists() and _ours(target):
        remove_file(root, target, report, dry_run)
    remove_shared_block(root, HOST, report, dry_run)
    return report


def status(root: Path) -> list[str]:
    root = Path(root)
    installed = (root / EXTENSION).exists() and _ours(root / EXTENSION)
    lines = ["extension: " + (EXTENSION.as_posix() if installed else "not installed")
             + " (loaded once the project is trusted in Pi)",
             "instruction block: " + ("present" if has_block(context_file(root, HOST))
                                      else "missing") + " (AGENTS.md, plumb turn start/end)"]
    lines += marker_lines(installed, "by the extension in Pi's process environment")
    lines += prompt_lines(root, installed, "before_agent_start")
    return lines
