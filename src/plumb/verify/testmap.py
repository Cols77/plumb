"""The code-to-test map (spec 7.1), cached by file fingerprint and written as grep-able text.

Built from ``verified_by`` links, ``sr`` markers, the import closure of each test module
(conftest files above it included) and test naming. ``.plumb/cache/test_map.json`` keeps
each Python file's parse keyed by ``(size, mtime_ns)``, so a warm build re-parses only the
files that changed. ``.plumb/test_map.txt`` is the text an agent greps.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterable, Mapping
from pathlib import Path, PurePosixPath
from typing import Any

from plumb.normalize import canonical_json, sha256_bytes, sha256_text

CACHE_VERSION = 1
HEADER = "# plumb test map v1 -- generated by `plumb tests map`; grep me"
_SKIP_DIRS = frozenset({"__pycache__", ".venv", "venv", ".git", ".plumb", "node_modules",
                        ".pytest_cache", ".ruff_cache", ".mypy_cache", "build", "dist"})


def is_test_file(rel: str, test_dirs: Iterable[str]) -> bool:
    pure = PurePosixPath(rel)
    if pure.suffix != ".py" or not (pure.name.startswith("test_") or pure.stem.endswith("_test")):
        return False
    return any(rel == d or rel.startswith(d.rstrip("/") + "/") for d in test_dirs)


def module_name(rel: str) -> str:
    """``src/plumb/links.py`` -> ``plumb.links``; ``pkg/__init__.py`` -> ``pkg``."""
    base = rel[:-3] if rel.endswith(".py") else rel
    parts = [p for p in base.split("/") if p]
    if parts and parts[0] == "src":
        parts = parts[1:]
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _scan(root: Path, dirs: Iterable[str]) -> dict[str, str]:
    """``{rel: "size:mtime_ns"}`` for every ``.py`` file under ``dirs``."""
    out: dict[str, str] = {}
    for d in dirs:
        base = root / d
        if not base.is_dir():
            continue
        stack = [base]
        while stack:
            cur = stack.pop()
            try:
                entries = list(os.scandir(cur))
            except OSError:
                continue
            for entry in entries:
                if entry.is_dir(follow_symlinks=False):
                    if entry.name not in _SKIP_DIRS and not entry.name.startswith("."):
                        stack.append(Path(entry.path))
                elif entry.name.endswith(".py"):
                    try:
                        st = entry.stat()
                    except OSError:
                        continue
                    rel = Path(entry.path).relative_to(root).as_posix()
                    out[rel] = f"{st.st_size}:{st.st_mtime_ns}"
    return out


def _parse_file(root: Path, rel: str, fp: str, test: bool) -> dict[str, Any]:
    from plumb.verify import markers
    from plumb.verify.imports import edges_of

    raw = (root / rel).read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return {"fp": fp, "hash": sha256_bytes(raw), "edges": [], "test": test}
    digest = sha256_bytes(raw) if "\x00" in text else sha256_text(text)  # as file_digest
    info: dict[str, Any] = {"fp": fp, "hash": digest, "test": test}
    tree = markers.parse(text)
    info["edges"] = [[m, lvl, list(names)] for m, lvl, names in edges_of(tree)] if tree else []
    if test:
        info["nodes"] = markers.test_nodes(text, rel, tree) if tree else {}
        info["markers"] = {k: sorted(v) for k, v in
                           markers.collect_markers(text, rel, tree).items()} if tree else {}
        info["strings"] = sorted(_path_like_strings(tree)) if tree else []
    return info


def _path_like_strings(tree: Any) -> set[str]:
    import ast

    out: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            value = node.value
            if 3 <= len(value) <= 300 and ("/" in value or "." in value):
                out.add(value)
    return out


class TestMap:
    """The built map. ``files`` holds each Python file's cached parse."""

    __test__ = False

    def __init__(self, root: Path, files: dict[str, dict[str, Any]],
                 direct: dict[str, list[str]], records: dict[str, list[str]],
                 implemented: dict[str, list[str]], test_dirs: tuple[str, ...],
                 parsed: int) -> None:
        self.root = root
        self.files = files
        self.direct = direct
        self.records = records
        self.implemented = implemented      # path -> requirement ids implemented by it
        self.test_dirs = test_dirs
        self.parsed = parsed
        self.test_files = sorted(r for r, i in files.items() if i.get("test"))
        self.closures: dict[str, dict[str, int]] = {t: self._closure(t) for t in self.test_files}
        self.importers: dict[str, dict[str, int]] = {}
        for test, depths in self.closures.items():
            for path, depth in depths.items():
                if path != test:
                    self.importers.setdefault(path, {})[test] = depth
        self.naming: dict[str, list[str]] = {}
        by_name: dict[str, list[str]] = {}
        for rel, info in files.items():
            if not info.get("test"):
                by_name.setdefault(PurePosixPath(rel).name, []).append(rel)
        for test in self.test_files:
            name = PurePosixPath(test).name
            stem = name[5:] if name.startswith("test_") else name[:-8] + ".py"
            for src in by_name.get(stem, ()):
                self.naming.setdefault(src, []).append(test)

    def _conftests(self, test: str) -> list[str]:
        parts = PurePosixPath(test).parts[:-1]
        out = []
        for i in range(len(parts), -1, -1):
            cand = "/".join([*parts[:i], "conftest.py"])
            if cand in self.files:
                out.append(cand)
        return out

    def _closure(self, test: str) -> dict[str, int]:
        from collections import deque

        depths = {test: 0}
        queue = deque([test])
        for conf in self._conftests(test):
            if conf not in depths:
                depths[conf] = 1
                queue.append(conf)
        while queue:
            cur = queue.popleft()
            for nxt in self.direct.get(cur, ()):
                if nxt not in depths:
                    depths[nxt] = depths[cur] + 1
                    queue.append(nxt)
        return depths

    # -- queries
    def covering(self, path: str) -> list[str]:
        """Test files covering ``path``: importers nearest first, then naming."""
        importers = self.importers.get(path, {})
        out = sorted(importers, key=lambda t: (importers[t], t))
        out += [t for t in sorted(self.naming.get(path, ())) if t not in importers]
        return out

    def reason(self, path: str, test: str) -> str | None:
        if test in self.importers.get(path, {}):
            return "import"
        if test in self.naming.get(path, ()):
            return "naming"
        return None

    def mentions(self, path: str) -> list[str]:
        """Test files whose string constants name ``path`` or its module."""
        module = module_name(path) if path.endswith(".py") else None
        out = []
        for test in self.test_files:
            if test == path:
                continue
            for value in self.files[test].get("strings", ()):
                if path in value or (module and module in value.split()):
                    out.append(test)
                    break
        return out

    def closure_hash(self, test_file: str) -> str | None:
        depths = self.closures.get(test_file)
        if depths is None:
            return None
        pairs = sorted((p, self.files[p]["hash"]) for p in depths if p in self.files)
        return sha256_bytes(canonical_json(pairs))

    def node_hash(self, node_id: str) -> str | None:
        from plumb.verify.markers import strip_param

        test_file = node_id.split("::", 1)[0]
        info = self.files.get(test_file)
        if info is None:
            return None
        if "::" not in node_id:
            return info["hash"]
        return info.get("nodes", {}).get(strip_param(node_id))

    def nodes_of(self, test_file: str) -> list[str]:
        return sorted(self.files.get(test_file, {}).get("nodes", {}))

    def as_dict(self) -> dict[str, Any]:
        sources = {}
        for path, info in sorted(self.files.items()):
            if info.get("test"):
                continue
            tests = self.verified_tests(path) + [t for t in self.covering(path)
                                                 if t not in self.verified_tests(path)]
            if tests:
                sources[path] = tests
        return {
            "sources": sources,
            "records": {k: v for k, v in sorted(self.records.items())},
            "tests": {t: sorted((p for p in d if p != t), key=lambda p: (d[p], p))
                      for t, d in self.closures.items()},
        }

    def verified_tests(self, path: str) -> list[str]:
        out: list[str] = []
        for rid in self.implemented.get(path, ()):
            for test in self.records.get(rid, ()):
                if test not in out:
                    out.append(test)
        return out

    def text(self) -> str:
        data = self.as_dict()
        lines = [HEADER]
        lines += [f"{src} -> {' '.join(tests)}" for src, tests in data["sources"].items()]
        lines += [f"{rid} -> {' '.join(tests)}" for rid, tests in data["records"].items() if tests]
        lines += [f"{test} <- {' '.join(deps)}" for test, deps in data["tests"].items() if deps]
        return "\n".join(lines) + "\n"


def _record_links(core: Any) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """``(records -> verified_by tests, path -> requirement ids implemented by it)``."""
    from plumb.hashing import clean_rel_path, target_path

    records: dict[str, list[str]] = {}
    implemented: dict[str, list[str]] = {}
    try:
        index = core.index()
    except Exception:  # a broken record store never breaks the map
        return records, implemented
    for record in index.values():
        for link in record.links:
            if link.kind == "verified_by":
                target = link.target.test or link.target.path
                if target and target not in records.setdefault(record.id, []):
                    records[record.id].append(target)
            elif link.kind == "implemented_by":
                path = target_path(link.target)
                rel = clean_rel_path(path) if path else None
                if rel:
                    implemented.setdefault(rel, [])
                    if record.id not in implemented[rel]:
                        implemented[rel].append(record.id)
        implemented.setdefault(record.path, []).append(record.id)
    return records, implemented


def _load_cache(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict) or data.get("v") != CACHE_VERSION:
        return {}
    return data


def _write_if_changed(path: Path, text: str) -> None:
    try:
        if path.exists() and path.read_text(encoding="utf-8") == text:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    except OSError:
        pass


def scan_files(root: Path, config: Any) -> dict[str, str]:
    """``{rel: "size:mtime_ns"}`` of every Python file the map reads (about 10 ms)."""
    dirs = tuple(dict.fromkeys([*config.source_dirs, *config.test_dirs]))
    scanned = _scan(root, dirs)
    for rel in ("conftest.py",):
        try:
            st = (root / rel).stat()
            scanned[rel] = f"{st.st_size}:{st.st_mtime_ns}"
        except OSError:
            pass
    return scanned


class MapUnavailable(Exception):
    """The test map would take longer to build than a hook may spend (R5): the hook falls
    back to the unknown-coverage sample and the map is built outside its budget."""


def build_map(core: Any, *, rebuild: bool = False, write_text: bool = True,
              max_parse: int | None = None) -> TestMap:
    """Build (or refresh from the cache) the test map of ``core``'s repository.

    ``max_parse``: raise ``MapUnavailable`` instead of parsing more files than that (a cold
    or badly stale cache in a hook: about 20 ms a file, seconds on a real repository)."""
    from plumb.verify.imports import known_files, resolve_edge_rel

    root = Path(core.root)
    paths = core.paths
    config = core.config
    source_dirs = tuple(config.source_dirs)
    test_dirs = tuple(config.test_dirs)
    dirs = tuple(dict.fromkeys([*source_dirs, *test_dirs]))
    scanned = scan_files(root, config)
    cache = {} if rebuild else _load_cache(paths.test_map_json)
    cached_files: Mapping[str, Any] = cache.get("files", {})
    if max_parse is not None:
        stale = sum(1 for rel, fp in scanned.items()
                    if not (isinstance(cached_files.get(rel), dict)
                            and cached_files[rel].get("fp") == fp))
        if stale > max_parse:
            raise MapUnavailable(f"{stale} files to parse")
    files: dict[str, dict[str, Any]] = {}
    parsed = 0
    for rel, fp in sorted(scanned.items()):
        test = is_test_file(rel, test_dirs)
        old = cached_files.get(rel)
        if isinstance(old, dict) and old.get("fp") == fp and old.get("test") == test:
            files[rel] = old
            continue
        try:
            files[rel] = _parse_file(root, rel, fp, test)
        except OSError:
            continue
        parsed += 1
    same_set = set(cached_files) == set(files)
    old_direct: Mapping[str, list[str]] = cache.get("direct", {}) if same_set else {}
    direct: dict[str, list[str]] = {}
    # existence answers come from the scanned set: a changed file set re-resolves every
    # edge, and a stat per candidate costs seconds on Windows (spec 10)
    exists = known_files(root, scanned, dirs)
    for rel, info in files.items():
        old_info = cached_files.get(rel)
        if rel in old_direct and old_info is info:
            direct[rel] = old_direct[rel]
            continue
        found: set[str] = set()
        for edge in info.get("edges", ()):
            found |= resolve_edge_rel(rel, (edge[0], edge[1], tuple(edge[2])), source_dirs,
                                      exists)
        direct[rel] = sorted(found)
    if parsed or not same_set or rebuild or not paths.test_map_json.exists():
        try:
            paths.cache.mkdir(parents=True, exist_ok=True)
            paths.test_map_json.write_text(
                json.dumps({"v": CACHE_VERSION, "files": files, "direct": direct}),
                encoding="utf-8")
        except OSError:
            pass
    records, implemented = _record_links(core)
    tmap = TestMap(root, files, direct, records, implemented, test_dirs, parsed)
    for test in tmap.test_files:
        for node, marks in files[test].get("markers", {}).items():
            for rid in marks:
                bucket = tmap.records.setdefault(rid, [])
                if node not in bucket:
                    bucket.append(node)
    if write_text:
        _write_if_changed(paths.test_map_txt, tmap.text())
    return tmap
