import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { open, row, shot } from './helpers';

test('diagram zooms, resets, downloads and shows its source', async ({ page }, info) => {
  await open(page, 'demo-session', 'demo-card-1');
  const image = page.locator('.diagram-viewport img');
  await expect(image).toBeVisible();
  expect((await image.getAttribute('alt'))?.length).toBeGreaterThan(0);
  const width = () => image.evaluate(node => node.getBoundingClientRect().width);
  const fitted = await width();
  const zoom = page.getByLabel('Diagram zoom');
  await expect(zoom).toHaveText('100%');
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await expect(zoom).toHaveText('125%');
  expect(await width()).toBeGreaterThan(fitted);
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await expect(zoom).toHaveText('150%');
  await page.getByRole('button', { name: 'Zoom out' }).click();
  await expect(zoom).toHaveText('125%');
  await shot(page, info, 'diagram-zoomed');
  await page.getByRole('button', { name: 'Fit' }).click();
  await expect(zoom).toHaveText('100%');
  expect(await width()).toBe(fitted);
  await page.getByRole('button', { name: 'Zoom out' }).click();
  await expect(zoom).toHaveText('75%');
  expect(await width()).toBeLessThan(fitted);
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download SVG' }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe('plumb-diagram.svg');
  const svg = readFileSync((await file.path())!, 'utf8');
  expect(svg).toContain('<svg');
  expect(svg).toContain('Saved rows');
  expect(svg).not.toContain('<script');
  await page.getByRole('button', { name: 'Show source' }).click();
  await expect(page.getByLabel('Sanitized SVG source')).toContainText('<svg');
  await page.getByRole('button', { name: 'Hide source' }).click();
  await expect(page.getByLabel('Sanitized SVG source')).toHaveCount(0);
  await row(page, 'Choose when to send notifications').click();
  await expect(page.locator('.diagram')).toHaveCount(0);
});
